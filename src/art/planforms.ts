/**
 * Original top-down outlines ("planforms") for each aircraft, drawn by hand for
 * this site from general published three-view shapes. They are simplified
 * illustrations, not tracings of photographs or manufacturer drawings.
 *
 * Coordinates describe the right half of the aircraft, nose at the top:
 * `y` runs from the nose (0) to the tail (about 100), `x` outward from the
 * centreline. The renderer mirrors the half and rescales it so the drawing
 * matches the record's published length and wingspan, so every jet can be
 * shown at true relative scale.
 */

export type Pt = readonly [x: number, y: number]

export interface Fin {
  /** Root position (x from centreline; 0 = single fin on the centreline). */
  x: number
  root: readonly [y0: number, y1: number]
  /** Tip position as seen from above: canted fins appear offset outward. */
  tipX: number
  tip: readonly [y0: number, y1: number]
}

export interface Nozzle {
  /** Centre x (0 = single engine on the centreline). */
  x: number
  /** Aft edge. */
  y: number
  width: number
  length: number
}

export interface Planform {
  outline: readonly Pt[]
  canopy: { y0: number; y1: number; width: number }
  fins: readonly Fin[]
  nozzles: readonly Nozzle[]
  /** Dark intake openings, right side only (mirrored). */
  intakes?: readonly (readonly Pt[])[]
  /** Panel and control-surface lines, right side only (mirrored). */
  lines?: readonly (readonly Pt[])[]
  /** Shown under the drawing when the pose needs explaining (e.g. swing wings). */
  pose?: string
}

const single = (root: Fin['root'], tip: Fin['tip']): Fin => ({ x: 0, root, tipX: 0, tip })

